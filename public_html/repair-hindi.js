function repairHindi(input) {
  let s = String(input);
  s = s.replace(/\u094D[ \t]+/g, "\u094D");
  s = s.replace(/[ \t]+([\u093E\u0940-\u094C\u0902\u0903])/g, "$1");
  s = s.replace(/\u093F{2,}/g, "\u093F");
  const sorted = pairs.sort((a, b) => b[0].length - a[0].length);
  for (const [bad, good] of sorted) s = s.split(bad).join(good);
  s = s.replace(/के सा(?=[\s।,])/g, "के साथ");
  s = s.replace(/साइबर\s+गी/g, "साइबर ठगी");
  s = s.replace(/\sा(?=[\s—\-।,])/g, " था");
  s = s.replace(/\sीं/g, " थीं");
  s = s.replace(/\sी(?=[\s।,])/g, " थी");
  s = s.replace(/([ेै])\s+े(?=[\s,।])/g, "$1 थे");
  s = s.replace(/\sीक/g, " ठीक");
  s = s.replace(/\sोड़ी/g, " थोड़ी");
  s = s.replace(/आ घंटे/g, "आठ घंटे");
  s = s.replace(/नगर नगम/g, "नगर निगम");
  s = s.replace(/सरकारी नयम/g, "सरकारी नियम");
  s = s.replace(/([^ा])जस(?=[\s])/g, "$1जिस");
  s = s.replace(/नीत,/g, "नीति,");
  s = s.replace(/मै तक/g, "मैट तक");
  s = s.replace(/कचरा नहीं उा/g, "कचरा नहीं उठा");
  s = s.replace(/कतना अंतर/g, "कितना अंतर");
  s = s.replace(/विह अंतर/g, "वह अंतर");
  s = s.replace(/कस पर/g, "किस पर");
  s = s.replace(/भाा/g, "भाषा");
  s = s.replace(/संगन/g, "संगठन");
  s = s.replace(/दिाविा/g, "दावा");
  s = s.replace(/विैसी/g, "वैसी");
  s = s.replace(/व्यविस्था/g, "व्यवस्था");
  s = s.replace(/विास्तवि/g, "वास्तव");
  s = s.replace(/मौजूदि/g, "मौजूद");
  s = s.replace(/क् या/g, "क्या");
  s = s.replace(/ज् या/g, "ज्या");
  s = s.replace(/व् य/g, "व्य");
  s = s.replace(/रू पि/g, "रूप");
  s = s.replace(/रू प/g, "रूप");
  s = s.replace(/स् तर/g, "स्तर");
  s = s.replace(/स् वयं/g, "स्वयं");
  s = s.replace(/स् वास्थ्य/g, "स्वास्थ्य");
  s = s.replace(/स् ानीय/g, "स्थानीय");
  s = s.replace(/स् ोरी/g, "स्टोरी");
  s = s.replace(/स् वीकार/g, "स्वीकार");
  s = s.replace(/द्व ारा/g, "द्वारा");
  s = s.replace(/स्क्र ीन/g, "स्क्रीन");
  s = s.replace(/असाइनमेंटट/g, "असाइनमेंट");
  s = s.replace(/निनिशाना/g, "निशाना");
  s = s.replace(/गए े/g, "गए थे");
  s = s.replace(/ {2,}/g, " ");
  return s;
}

